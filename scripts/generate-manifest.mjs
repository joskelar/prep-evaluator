import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const projectRoot = path.resolve(__dirname, '..');
const publicDir = path.join(projectRoot, 'public');
const banksDir = path.join(publicDir, 'data', 'banks');
const stimuliDir = path.join(publicDir, 'data', 'stimuli');
const manifestPath = path.join(publicDir, 'data', 'config', 'bank-manifest.json');

function walk(dir) {
  let results = [];
  const list = fs.readdirSync(dir);
  list.forEach((file) => {
    const filePath = path.join(dir, file);
    const stat = fs.statSync(filePath);
    if (stat && stat.isDirectory()) {
      results = results.concat(walk(filePath));
    } else {
      if (file.endsWith('.json')) {
        results.push(filePath);
      }
    }
  });
  return results;
}

function generateManifest() {
  console.log('Generating manifest...');
  
  const banks = [];
  const stimuli = [];

  if (fs.existsSync(banksDir)) {
    const files = walk(banksDir);
    files.forEach((filePath) => {
      const relPath = path.relative(publicDir, filePath).replace(/\\/g, '/');
      // Relative path format: data/banks/cognitive/analogies/set-001.json
      const parts = relPath.split('/');
      // parts[0] = 'data', parts[1] = 'banks', parts[2] = 'cognitive' (area), parts[3] = 'analogies' (category), parts[4] = 'set-001.json'
      if (parts.length >= 5) {
        const area = parts[2];
        const category = parts[3];
        banks.push({
          path: relPath,
          area,
          category
        });
      }
    });
  }

  if (fs.existsSync(stimuliDir)) {
    const files = walk(stimuliDir);
    files.forEach((filePath) => {
      const relPath = path.relative(publicDir, filePath).replace(/\\/g, '/');
      const parts = relPath.split('/');
      // parts[0] = 'data', parts[1] = 'stimuli', parts[2] = 'cognitive' (area), parts[3] = 'diagrams' (category/type)
      if (parts.length >= 5) {
        const area = parts[2];
        const category = parts[3];
        stimuli.push({
          path: relPath,
          area,
          category
        });
      }
    });
  }

  const studyCards = [];
  const studyCardsDir = path.join(publicDir, 'data', 'study-cards');
  if (fs.existsSync(studyCardsDir)) {
    const files = walk(studyCardsDir);
    files.forEach((filePath) => {
      const relPath = path.relative(publicDir, filePath).replace(/\\/g, '/');
      const parts = relPath.split('/');
      if (parts.length >= 5) {
        const area = parts[2];
        const category = parts[3];
        studyCards.push({
          path: relPath,
          area,
          category
        });
      }
    });
  }

  // Sort deterministically by path
  banks.sort((a, b) => a.path.localeCompare(b.path));
  stimuli.sort((a, b) => a.path.localeCompare(b.path));
  studyCards.sort((a, b) => a.path.localeCompare(b.path));

  const manifest = {
    version: 1,
    banks,
    stimuli,
    studyCards,
    notes: 'Auto-generated by scripts/generate-manifest.mjs'
  };

  fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2), 'utf-8');
  console.log(`Manifest successfully generated at ${manifestPath}`);
  console.log(`Total question sets: ${banks.length}`);
  console.log(`Total stimuli sets: ${stimuli.length}`);
  console.log(`Total study card sets: ${studyCards.length}`);
}

generateManifest();
